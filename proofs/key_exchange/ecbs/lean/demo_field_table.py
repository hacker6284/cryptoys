#!/usr/bin/env python3
"""Regenerate the Demo climb table.

Each length-7 trit list is one `DemoRow`: the two rung gaps, the cubed gap,
and the answer `specInv` returns. Lean decides the rows in bands of 27.
This script only proposes the numbers. `rowOk` in `DemoFieldTab.lean` is
the check. Proof-only. Not a security claim.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "EcbsLink2" / "Link2"
N, K, BENCH = 7, 5, 20
BAND = 9
COUNT = 3**7  # 2187, including the zero home at index 0


def coeff(xs, i):
    return xs[i] if i < len(xs) else 0


def set_at(xs, i, a):
    if i >= len(xs):
        return xs
    ys = xs[:]
    ys[i] = a
    return ys


def trit_add(a, b):
    return (a + b) % 3


def flip(c):
    return 0 if c == 0 else 3 - c


def school_row(n, first, i, mirror, strip):
    for j in range(n):
        d = coeff(first, j)
        if d != 0:
            laid = flip(d) if mirror else d
            strip = set_at(strip, i + j, trit_add(coeff(strip, i + j), laid))
    return strip


def school(n, first, second, strip, mirror):
    for i in reversed(range(n)):
        c = coeff(second, i)
        if c != 0:
            strip = school_row(n, first, i, (c == 2) != mirror, strip)
    return strip


def fold_high(n, gap, e, strip):
    c = coeff(strip, e)
    if c == 0 or e < n:
        return strip
    cleared = set_at(strip, e, 0)
    once = set_at(cleared, e - n, trit_add(coeff(cleared, e - n), c))
    return set_at(once, e - gap, trit_add(coeff(once, e - gap), c))


def reduce_strip(n, gap, strip):
    extra = len(strip) - n
    if extra < 0:
        extra = 0
    for d in reversed(range(extra)):
        strip = fold_high(n, gap, n + d, strip)
    return strip


def field_mul(x, y):
    strip = school(N, x, y, [0] * BENCH, False)
    return reduce_strip(N, N - K, strip)[:N]


def field_cube(x):
    strip = [0] * BENCH
    for i, c in enumerate(x[:N]):
        if c != 0:
            strip = set_at(strip, 3 * i, c)
    return reduce_strip(N, N - K, strip)[:N]


def cube_times(x, t):
    for _ in range(t):
        x = field_cube(x)
    return x


def inv_rung(x, g, tally, rung, last):
    g1 = field_mul(g, cube_times(g, tally))
    tally1 = tally if last else 2 * tally
    if rung == 2:
        return field_mul(x, field_cube(g1)), (tally1 if last else tally1 + 1)
    return g1, tally1


def mirror(xs):
    return [flip(c) for c in xs]


WHITE = [1, 0, 0, 0, 0, 0, 0]
RED = [2, 0, 0, 0, 0, 0, 0]


def digits(n):
    return [
        (n // 729) % 3,
        (n // 243) % 3,
        (n // 81) % 3,
        (n // 27) % 3,
        (n // 9) % 3,
        (n // 3) % 3,
        n % 3,
    ]


def climb(x):
    g1, t1 = inv_rung(x, x, 1, 2, False)
    g2, t2 = inv_rung(x, g1, 3, 1, True)
    if (t1, t2) != (3, 3):
        raise SystemExit(f"tally {x}: {t1}, {t2}")
    gap = field_cube(g2)
    prod = field_mul(gap, x)
    if prod == WHITE:
        return g1, g2, gap, gap, True
    if prod == RED:
        return g1, g2, gap, mirror(gap), False
    raise SystemExit(f"product is neither peg for {x}: {prod}")


def lit(xs):
    return "[" + ", ".join(str(c) for c in xs) + "]"


def row_lit(x, g1, g2, gap, ans, white):
    flag = "true" if white else "false"
    return f"  ⟨{lit(x)}, {lit(g1)}, {lit(g2)}, {lit(gap)}, {lit(ans)}, {flag}⟩"


def check_against_old():
    """The previous one-line theorems, if they are still on disk."""
    import re
    from collections import defaultdict

    files = [OUT / f"DemoField{i}.lean" for i in (1, 2, 3, 4)]
    if not all(p.exists() and "theorem demoR1_" in p.read_text() for p in files):
        return
    text = "\n".join(p.read_text() for p in files)
    found = re.findall(r"^theorem (demo(?:R1|R2|C|Inv)_[0-9]+) : (.+)$", text, re.M)
    groups = defaultdict(dict)
    for name, stmt in found:
        kind, _key = name.split("_", 1)
        groups[name.split("_", 1)[1]][kind] = re.findall(r"\[[0-9, ]+\]", stmt)
    bad = 0
    for n in range(1, COUNT):
        x = digits(n)
        g1, g2, gap, ans, white = climb(x)
        key = "".join(str(c) for c in x)
        g = groups.get(key)
        if g is None:
            bad += 1
            continue
        if g["demoR1"][-1] != lit(g1) or g["demoR2"][-1] != lit(g2):
            bad += 1
        if g["demoC"][-1] != lit(gap) or g["demoInv"][-1] != lit(ans):
            bad += 1
        if white and "whiteHole0" not in text[text.find(f"theorem demoM_{key}") : text.find(f"theorem demoM_{key}") + 200]:
            pass
    if bad:
        raise SystemExit(f"generator disagrees with the old theorems: {bad}")
    print(f"generator matches the old DemoField theorems ({COUNT - 1} nonzero)")


HEADER = """/-
  Generated by `demo_field_table.py`. Do not edit.
  One Demo climb per base-3 index, in bands of 9. Index 0 is the zero home.
  Proof-only. Not a security claim.
-/
"""


def emit(rows):
    nb = COUNT // BAND
    if nb * BAND != COUNT:
        raise SystemExit(f"band {BAND} does not divide {COUNT}")
    parts = [
        HEADER,
        "import EcbsLink2.Link2.DemoFieldTab\n\n",
        "namespace EcbsLink2.Link2\n\n",
    ]
    for k in range(nb):
        body = ",\n".join(rows[k * BAND : (k + 1) * BAND])
        parts.append(f"def demoBand{k} : List DemoRow := [\n{body}\n]\n\n")
    group = 81
    gnames = ["A", "B", "C"]
    for g, name in enumerate(gnames):
        lo = g * group
        arms = "\n".join(
            f"  | {i} => demoBand{lo + i}" for i in range(group)
        )
        parts.append(
            f"def demoBand{name} : Nat → List DemoRow\n{arms}\n  | _ => []\n\n"
        )
    parts.append(
        "def demoBand (k : Nat) : List DemoRow :=\n"
        "  if k < 81 then demoBandA k\n"
        "  else if k < 162 then demoBandB (k - 81)\n"
        "  else demoBandC (k - 162)\n\n"
    )
    for k in range(nb):
        parts.append(
            f"theorem demoBandLen{k} : demoBand{k}.length = {BAND} := by\n  decide\n\n"
        )
    for g, name in enumerate(gnames):
        lo = g * group
        arms = "\n".join(f"  | {i} => exact demoBandLen{lo + i}" for i in range(group))
        parts.append(
            f"theorem demoBandLen{name} (k : Nat) (hk : k < {group}) :\n"
            f"    (demoBand{name} k).length = {BAND} := by\n"
            f"  match k with\n{arms}\n  | n + {group} => omega\n\n"
        )
    parts.append(
        f"theorem demoBandLen (k : Nat) (hk : k < {nb}) : (demoBand k).length = {BAND} := by\n"
        "  by_cases h1 : k < 81\n"
        "  · unfold demoBand\n"
        "    rw [if_pos h1]\n"
        "    exact demoBandLenA k h1\n"
        "  · by_cases h2 : k < 162\n"
        "    · have hk2 : k - 81 < 81 := by omega\n"
        "      unfold demoBand\n"
        "      rw [if_neg h1, if_pos h2]\n"
        "      exact demoBandLenB (k - 81) hk2\n"
        "    · have hk3 : k - 162 < 81 := by omega\n"
        "      unfold demoBand\n"
        "      rw [if_neg h1, if_neg h2]\n"
        "      exact demoBandLenC (k - 162) hk3\n\n"
    )
    for k in range(nb):
        arms_j = "\n".join(f"  | {j} => rfl" for j in range(BAND))
        parts.append(
            f"theorem demoBandX{k} (j : Nat) (hj : j < {BAND}) :\n"
            f"    (demoBand{k}[j]'(by rw [demoBandLen{k}]; exact hj)).x =\n"
            f"      expected ({BAND} * {k} + j) := by\n"
            f"  match j with\n{arms_j}\n"
            f"  | n + {BAND} => omega\n\n"
        )
    for g, name in enumerate(gnames):
        lo = g * group
        arms = "\n".join(
            f"  | {i} => exact demoBandX{lo + i} j hj"
            for i in range(group)
        )
        parts.append(
            f"theorem demoBandX{name} (k j : Nat) (hk : k < {group}) (hj : j < {BAND}) :\n"
            f"    ((demoBand{name} k)[j]'(by rw [demoBandLen{name} k hk]; exact hj)).x =\n"
            f"      expected ({BAND} * ({lo} + k) + j) := by\n"
            f"  match k with\n{arms}\n  | n + {group} => omega\n\n"
        )
    parts.append(
        f"theorem demoBandX (k j : Nat) (hk : k < {nb}) (hj : j < {BAND}) :\n"
        "    ((demoBand k)[j]'(by rw [demoBandLen k hk]; exact hj)).x =\n"
        f"      expected ({BAND} * k + j) := by\n"
        "  by_cases h1 : k < 81\n"
        "  · have hx := demoBandXA k j h1 hj\n"
        "    simpa [demoBand, h1] using hx\n"
        "  · by_cases h2 : k < 162\n"
        "    · have hk2 : k - 81 < 81 := by omega\n"
        "      have hx := demoBandXB (k - 81) j hk2 hj\n"
        "      have hshift : 9 * (81 + (k - 81)) + j = 9 * k + j := by omega\n"
        "      simpa [demoBand, h1, h2, hshift] using hx\n"
        "    · have hk3 : k - 162 < 81 := by omega\n"
        "      have hx := demoBandXC (k - 162) j hk3 hj\n"
        "      have hshift : 9 * (162 + (k - 162)) + j = 9 * k + j := by omega\n"
        "      simpa [demoBand, h1, h2, hshift] using hx\n\n"
        "end EcbsLink2.Link2\n"
    )
    (OUT / "DemoFieldRows.lean").write_text("".join(parts))
    chunk = (nb + 3) // 4
    for part in range(4):
        lo = part * chunk
        hi = min(lo + chunk, nb)
        lines = [
            HEADER,
            "import EcbsLink2.Link2.DemoFieldRows\n\n",
            "namespace EcbsLink2.Link2\n\n",
        ]
        for k in range(lo, hi):
            lines.append(
                f"theorem demoClimbBand{k} : demoChecked (demoBand {k}) = true := by\n"
                f"  decide\n\n"
            )
        lines.append("end EcbsLink2.Link2\n")
        (OUT / f"DemoField{part + 1}.lean").write_text("".join(lines))
    join = [
        HEADER,
        """import EcbsLink2.Link2.DemoField1
import EcbsLink2.Link2.DemoField2
import EcbsLink2.Link2.DemoField3
import EcbsLink2.Link2.DemoField4

namespace EcbsLink2.Link2

""",
    ]
    for g, name in enumerate(gnames):
        lo = g * group
        arms = "\n".join(
            f"  | {i} => exact demoClimbBand{lo + i}" for i in range(group)
        )
        join.append(
            f"theorem demoClimbBand{name} (k : Nat) (hk : k < {group}) :\n"
            f"    demoChecked (demoBand{name} k) = true := by\n"
            f"  match k with\n{arms}\n  | n + {group} => omega\n\n"
        )
    join.append(
        f"theorem demoClimbBand (k : Nat) (hk : k < {nb}) :\n"
        "    demoChecked (demoBand k) = true := by\n"
        "  by_cases h1 : k < 81\n"
        "  · simpa [demoBand, h1] using demoClimbBandA k h1\n"
        "  · by_cases h2 : k < 162\n"
        "    · have hk2 : k - 81 < 81 := by omega\n"
        "      simpa [demoBand, h1, h2] using demoClimbBandB (k - 81) hk2\n"
        "    · have hk3 : k - 162 < 81 := by omega\n"
        "      simpa [demoBand, h1, h2] using demoClimbBandC (k - 162) hk3\n\n"
        "end EcbsLink2.Link2\n"
    )
    (OUT / "DemoFieldJoin.lean").write_text("".join(join))
    print(f"wrote {COUNT} rows, {nb} bands")


def main():
    check_against_old()
    rows = []
    for n in range(COUNT):
        x = digits(n)
        if n == 0:
            rows.append(row_lit(x, x, x, x, x, True))
            continue
        g1, g2, gap, ans, white = climb(x)
        rows.append(row_lit(x, g1, g2, gap, ans, white))
    emit(rows)


if __name__ == "__main__":
    main()
