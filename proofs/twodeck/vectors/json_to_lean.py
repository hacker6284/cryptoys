def emit_ctr(_kind: str, items: list[dict]) -> str:
    lines = [
        "\nstructure CtrEncryptVec where\n",
        "  name : String\n",
        "  blocks : List (List Nat)\n",
        "  key : List Nat\n",
        "  nonce : List Nat\n",
        "  output : List (List Nat)\n",
        "\ndef ctrEncryptVecs : List CtrEncryptVec := [\n",
    ]
    for i, v in enumerate(items):
        comma = "," if i + 1 < len(items) else ""
        lines.append(
            "  { name := "
            + json.dumps(v["name"])
            + f",\n    blocks := {lean_list_of_lists(v['blocks'])},\n"
            f"    key := {lean_list(v['key'])},\n"
            f"    nonce := {lean_list(v['nonce'])},\n"
            f"    output := {lean_list_of_lists(v['output'])} }}{comma}\n"
        )
    lines.append("]\n")
    return "".join(lines)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--json", type=Path, default=DEFAULT_JSON)
    p.add_argument("--lean", type=Path, default=DEFAULT_LEAN)
    p.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the Lean file does not match a fresh emit (no write)",
    )
    args = p.parse_args()
    doc = json.loads(args.json.read_text())
    text = emit(doc)
    if args.check:
        current = args.lean.read_text() if args.lean.exists() else ""
        if current != text:
            print(
                f"{args.lean} is stale; run proofs/twodeck/vectors/regen.sh "
                "or json_to_lean.py",
                file=sys.stderr,
            )
            return 1
        print(f"{args.lean} matches {args.json}")
        return 0
    args.lean.parent.mkdir(parents=True, exist_ok=True)
    args.lean.write_text(text)
    print(f"wrote {args.lean} ({doc.get('schema')} schema, {len(doc['vectors'])} vectors)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
