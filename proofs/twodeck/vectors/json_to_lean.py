    lines = [
        "\nstructure CounterDeckVec where\n",
        "  name : String\n",
        "  nonce : List Nat\n",
        "  index : Nat\n",
        "  deck : List Nat\n",
        "\ndef counterDeckVecs : List CounterDeckVec := [\n",
    ]
